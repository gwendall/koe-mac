import AppKit
import Carbon.HIToolbox
import CoreGraphics

// Types the words through the clipboard and ⌘V, the way every app accepts
// text, then checks they arrived. Arrived (or the app cannot say): the
// clipboard gets back what it held. Not typed: the words stay on the
// clipboard, to paste by hand. Needs Accessibility.
@MainActor
enum Paster {
    enum Result: Equatable {
        case typed            // the field shows the words
        case probably         // ⌘V went to an app that cannot say
        case copied(String)   // not typed: on the clipboard, and why
    }

    // Clipboard managers that honor these skip text Koe only passes through.
    private static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let generated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    // `follows`: what Koe typed last in that app, when nothing was typed or
    // clicked since, so the cursor is still right after it.
    static func type(_ text: String, into verdict: Target.Verdict, submit: Bool, follows: Character? = nil) async -> Result {
        var text = text
        switch verdict {
        case .field(let field): text = joined(text, after: Target.characterBeforeCursor(in: field.element) ?? follows)
        case .unknown: text = joined(text, after: follows)
        case .nowhere: break
        }
        let board = NSPasteboard.general
        let saved = snapshot(board)
        board.clearContents()
        board.declareTypes([.string, transient, generated], owner: nil)
        board.setString(text, forType: .string)
        board.setData(Data(), forType: transient)
        board.setData(Data(), forType: generated)
        let ours = board.changeCount

        let field: Target.Field?
        switch verdict {
        case .nowhere(let why):
            return .copied(why)
        case .field(let found):
            field = found
        case .unknown:
            field = nil
        }

        // Give the clipboard a beat to be readable by the other app.
        try? await Task.sleep(for: .milliseconds(50))
        press(vKey(), flags: .maskCommand)

        var result = Result.probably
        if let field {
            // Up to 0.9 s for the field to show the words.
            for _ in 0..<18 {
                try? await Task.sleep(for: .milliseconds(50))
                if let received = field.received(text) {
                    if received { result = .typed; break }
                } else {
                    break
                }
            }
            // Not the words as said, but the field changed: a terminal wraps
            // them, Claude Code folds a long paste into "[Pasted text]", an
            // app corrects them. They landed; only a field left as it was
            // didn't take them (and never gets Return).
            if result != .typed, field.received(text) == false, field.unchanged != false {
                result = .copied(Words.say("The field didn't take it"))
            }
        }

        if case .copied = result { return result }
        if submit {
            // Telegram, Slack and Electron apps need the paste settled first;
            // a modifier still held would turn Return into ⌘Return.
            try? await Task.sleep(for: .milliseconds(500))
            releaseModifiers()
            press(36, flags: []) // Return
        }
        // Long enough for the app to read it, short enough not to be noticed.
        try? await Task.sleep(for: .milliseconds(600))
        if board.changeCount == ours { restore(saved, to: board) }
        return result
    }

    // Right after a word or a full stop, a space: two dictations in a row
    // read as two sentences, not "one.Two". Never after an opening mark,
    // and never before the words' own punctuation.
    nonisolated static func joined(_ text: String, after before: Character?) -> String {
        guard let before, let first = text.first, !before.isWhitespace, !"([{\"'«“‘/-@#".contains(before),
              !first.isWhitespace, !",.;:!?)]}…".contains(first) else { return text }
        return " " + text
    }

    // The key that types "v" with ⌘ held, in the keyboard layout in use: on
    // Dvorak it is not the QWERTY V (9), which would send ⌘K. A layout that
    // cannot type Latin letters (Russian, Greek) leaves ⌘ shortcuts to its
    // Latin companion, as macOS does.
    static func vKey() -> CGKeyCode {
        let current = TISCopyCurrentKeyboardLayoutInputSource()?.takeRetainedValue()
        let latin = TISCopyCurrentASCIICapableKeyboardLayoutInputSource()?.takeRetainedValue()
        for source in [current, latin].compactMap({ $0 }) {
            if let key = key(typing: "v", in: source) { return key }
        }
        return 9
    }

    static func key(typing letter: Character, in source: TISInputSource) -> CGKeyCode? {
        guard let pointer = TISGetInputSourceProperty(source, kTISPropertyUnicodeKeyLayoutData) else { return nil }
        let data = Unmanaged<CFData>.fromOpaque(pointer).takeUnretainedValue() as Data
        return data.withUnsafeBytes { bytes -> CGKeyCode? in
            guard let layout = bytes.bindMemory(to: UCKeyboardLayout.self).baseAddress else { return nil }
            let command = UInt32((cmdKey >> 8) & 0xFF)
            for code in 0..<UInt16(128) {
                var dead: UInt32 = 0, length = 0
                var chars = [UniChar](repeating: 0, count: 4)
                let status = UCKeyTranslate(layout, code, UInt16(kUCKeyActionDown), command, UInt32(LMGetKbdType()),
                                            OptionBits(kUCKeyTranslateNoDeadKeysBit), &dead, 4, &length, &chars)
                if status == noErr, length == 1, Character(UnicodeScalar(chars[0]) ?? " ") == letter { return CGKeyCode(code) }
            }
            return nil
        }
    }

    // Copies text to the clipboard and leaves it there.
    static func copy(_ text: String) {
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(text, forType: .string)
    }

    private static func snapshot(_ board: NSPasteboard) -> [[NSPasteboard.PasteboardType: Data]] {
        (board.pasteboardItems ?? []).map { item in
            var copy: [NSPasteboard.PasteboardType: Data] = [:]
            for kind in item.types { if let data = item.data(forType: kind) { copy[kind] = data } }
            return copy
        }
    }

    private static func restore(_ saved: [[NSPasteboard.PasteboardType: Data]], to board: NSPasteboard) {
        board.clearContents()
        let items = saved.map { copy -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (kind, data) in copy { item.setData(data, forType: kind) }
            return item
        }
        if !items.isEmpty { board.writeObjects(items) }
    }

    // One key, with exactly these modifiers, whatever the user still holds.
    private static func press(_ key: CGKeyCode, flags: CGEventFlags) {
        let source = CGEventSource(stateID: .hidSystemState)
        for down in [true, false] {
            let event = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: down)
            event?.flags = flags
            event?.post(tap: .cghidEventTap)
        }
    }

    // An empty modifier change: no modifier stays down for what follows.
    private static func releaseModifiers() {
        let source = CGEventSource(stateID: .hidSystemState)
        let event = CGEvent(keyboardEventSource: source, virtualKey: 0, keyDown: true)
        event?.type = .flagsChanged
        event?.flags = []
        event?.post(tap: .cghidEventTap)
    }
}
